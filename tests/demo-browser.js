let frame = document.querySelector('#preview');
const results = document.querySelector('#results');
let passed = 0;
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const check = (condition, name) => {
    if (!condition) throw new Error(name);
    const item = document.createElement('li');
    item.className = 'test-result';
    item.textContent = 'PASS: ' + name;
    results.append(item);
    passed++;
};
const load = async (page, width) => {
    const next = frame.cloneNode();
    next.removeAttribute('src');
    frame.replaceWith(next);
    frame = next;
    frame.style.width = width + 'px';
    const token = String(Date.now()) + Math.random();
    const html = await (await fetch(`../docs/${page}.html?test=${token}`)).text();
    frame.srcdoc = html.replace('<head>', `<head><base href="${new URL('../docs/', location.href)}">`).replace('<body>', `<body data-test-token="${token}">`);
    const start = Date.now();
    while (frame.contentDocument?.body?.dataset.testToken !== token || frame.contentDocument.readyState === 'loading' || !frame.contentWindow.SearchController) {
        if (Date.now() - start > 15000) throw new Error(`Загрузка ${page}: ${frame.contentDocument?.readyState}`);
        await wait(50);
    }
    await Promise.race([frame.contentDocument.fonts.ready, wait(1000)]);
    await wait(120);
    return frame.contentDocument;
};
const visible = doc => [...doc.querySelectorAll('.product-tile--favorite')].filter(card => !card.hidden);
const testFavorites = async width => {
    let doc = await load('favorite', width);
    const cards = visible(doc);
    const total = cards.length;
    check(total === 17, `${width}: все карточки избранного берутся из HTML`);
    const first = doc.querySelector('.favorites .favorite-btn');
    first.click();
    check(!first.classList.contains('active') && first.getAttribute('aria-pressed') === 'false' && visible(doc).length === total, `${width}: сердечко не удаляет товар`);
    first.click();
    check(first.classList.contains('active') && frame.contentWindow.getComputedStyle(first, '::before').content.includes('\ue944'), `${width}: активное сердечко использует залитый глиф`);
    const sequence = cards.map(card => card.querySelector('.product-tile__name').textContent).join();
    doc.querySelector('.favorites__more').click();
    doc.querySelectorAll('.favorites__page')[2].click();
    doc.querySelector('.favorites__sort').value = 'price-asc';
    doc.querySelector('.favorites__sort').dispatchEvent(new frame.contentWindow.Event('change'));
    check(visible(doc).map(card => card.querySelector('.product-tile__name').textContent).join() === sequence, `${width}: пагинация, сортировка и «ещё» не меняют товары`);
    const categories = doc.querySelectorAll('.favorites__category').length;
    const count = doc.querySelector('.favorites__count').textContent;
    doc.querySelector('[data-remove-category]').click();
    check(doc.querySelectorAll('.favorites__category').length === categories - 1 && visible(doc).length === total && doc.querySelector('.favorites__count').textContent === count, `${width}: крестик удаляет только пункт категории`);
    doc.querySelector('.favorites__clear').click();
    check(doc.querySelectorAll('.favorites .favorite-btn.active').length === 0 && visible(doc).length === total, `${width}: очистка только снимает сердечки`);
    doc = await load('favorite', width);
    check(visible(doc).length === total && doc.querySelectorAll('.favorites__category').length === categories && doc.querySelectorAll('.favorites .favorite-btn.active').length === total, `${width}: перезагрузка восстанавливает исходный HTML`);
};
