const checkButtonStyles = (doc, width) => {
    const view = doc.defaultView;
    let rules = '';
    const walk = items => [...items].forEach(rule => {
        if (rule.selectorText && /:(hover|active)/.test(rule.selectorText)) rules += rule.selectorText.replaceAll(':hover', '.ui-hover').replaceAll(':active', '.ui-active') + '{' + rule.style.cssText + '}';
        else if (rule.cssRules && (!rule.media || view.matchMedia(rule.conditionText).matches)) walk(rule.cssRules);
    });
    [...doc.styleSheets].forEach(sheet => { try { walk(sheet.cssRules); } catch {} });
    const style = doc.createElement('style'); style.textContent = rules; doc.head.append(style);
    const primary = [...doc.querySelectorAll('.btn-primary, .btn-dark')].find(el => !el.disabled && el.getClientRects().length);
    if (primary) {
        const dark = primary.classList.contains('btn-dark');
        check(view.getComputedStyle(primary).backgroundColor === (dark ? 'rgb(41, 41, 41)' : 'rgb(255, 98, 1)'), `${width}: кнопка normal по UI-киту`);
        const size = primary.getBoundingClientRect();
        for (const state of ['ui-hover', 'ui-active']) {
            primary.classList.add(state); doc.getAnimations().forEach(animation => animation.finish());
            const next = primary.getBoundingClientRect();
            check(view.getComputedStyle(primary).backgroundColor === (dark ? 'rgb(64, 66, 70)' : 'rgb(251, 126, 0)') && size.width === next.width && size.height === next.height, `${width}: primary ${state} без скачка размеров`);
            primary.classList.remove(state); doc.getAnimations().forEach(animation => animation.finish());
        }
    }
    style.remove();
};
